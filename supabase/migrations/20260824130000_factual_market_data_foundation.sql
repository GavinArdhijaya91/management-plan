create table public.market_product_source_bindings (
  id uuid primary key default extensions.gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id)
    on delete cascade,
  product_id uuid not null,
  market_source_id bigint not null,
  category_code text not null,
  external_identifier text not null
    check (char_length(trim(external_identifier)) between 1 and 200),
  country_code text references public.countries(code)
    on delete restrict,
  region_code text
    check (region_code is null or char_length(trim(region_code)) between 1 and 50),
  refresh_interval_minutes integer not null default 1440
    check (refresh_interval_minutes between 5 and 43200),
  is_active boolean not null default true,
  created_by uuid not null references public.profiles(user_id)
    on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint market_product_source_bindings_product_fkey
    foreign key (workspace_id, product_id)
    references public.market_products(workspace_id, id)
    on delete cascade,
  constraint market_product_source_bindings_source_category_fkey
    foreign key (market_source_id, category_code)
    references public.market_source_categories(market_source_id, category_code)
    on delete restrict,
  constraint market_product_source_bindings_identity_key
    unique (workspace_id, product_id, id, market_source_id, category_code),
  constraint market_product_source_bindings_external_key
    unique nulls not distinct (
      workspace_id,
      product_id,
      market_source_id,
      category_code,
      external_identifier,
      country_code,
      region_code
    )
);

create table public.market_observations (
  id uuid primary key default extensions.gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id)
    on delete cascade,
  product_id uuid not null,
  binding_id uuid not null,
  market_source_id bigint not null,
  category_code text not null,
  source_record_id text not null
    check (char_length(trim(source_record_id)) between 1 and 300),
  metric_code text not null
    check (metric_code ~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,119}$'),
  numeric_value numeric not null
    check (abs(numeric_value) < 1e30),
  unit_code text not null
    check (unit_code ~ '^[A-Za-z0-9][A-Za-z0-9._/%:-]{0,31}$'),
  observed_at timestamptz not null,
  fetched_at timestamptz not null default now(),
  source_url text not null
    check (source_url ~ '^https://' and char_length(source_url) <= 2048),
  raw_payload_sha256 text not null
    check (raw_payload_sha256 ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default now(),
  constraint market_observations_binding_fkey
    foreign key (
      workspace_id,
      product_id,
      binding_id,
      market_source_id,
      category_code
    ) references public.market_product_source_bindings(
      workspace_id,
      product_id,
      id,
      market_source_id,
      category_code
    ) on delete cascade,
  constraint market_observations_fetch_order_check
    check (fetched_at >= observed_at),
  constraint market_observations_source_record_key
    unique (binding_id, source_record_id, metric_code, observed_at)
);

create table public.market_source_documents (
  id uuid primary key default extensions.gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id)
    on delete cascade,
  product_id uuid not null,
  binding_id uuid not null,
  market_source_id bigint not null,
  category_code text not null,
  source_record_id text not null
    check (char_length(trim(source_record_id)) between 1 and 300),
  title text not null
    check (char_length(trim(title)) between 2 and 500),
  canonical_url text not null
    check (canonical_url ~ '^https://' and char_length(canonical_url) <= 2048),
  publisher_name text not null
    check (char_length(trim(publisher_name)) between 2 and 160),
  published_at timestamptz not null,
  fetched_at timestamptz not null default now(),
  language_code text
    check (language_code is null or language_code ~ '^[a-z]{2,3}(-[A-Z]{2})?$'),
  country_code text references public.countries(code)
    on delete restrict,
  raw_payload_sha256 text not null
    check (raw_payload_sha256 ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default now(),
  constraint market_source_documents_binding_fkey
    foreign key (
      workspace_id,
      product_id,
      binding_id,
      market_source_id,
      category_code
    ) references public.market_product_source_bindings(
      workspace_id,
      product_id,
      id,
      market_source_id,
      category_code
    ) on delete cascade,
  constraint market_source_documents_fetch_order_check
    check (fetched_at >= published_at),
  constraint market_source_documents_source_record_key
    unique (binding_id, source_record_id)
);

create type public.market_sync_outcome as enum (
  'running',
  'succeeded',
  'failed'
);

create table public.market_source_sync_runs (
  id uuid primary key default extensions.gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id)
    on delete cascade,
  product_id uuid not null,
  binding_id uuid not null,
  market_source_id bigint not null,
  category_code text not null,
  sync_outcome public.market_sync_outcome not null default 'running',
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  fetched_count integer not null default 0
    check (fetched_count between 0 and 1000000),
  accepted_count integer not null default 0
    check (accepted_count between 0 and fetched_count),
  error_code text
    check (error_code is null or error_code ~ '^[A-Z][A-Z0-9_]{1,79}$'),
  created_at timestamptz not null default now(),
  constraint market_source_sync_runs_binding_fkey
    foreign key (
      workspace_id,
      product_id,
      binding_id,
      market_source_id,
      category_code
    ) references public.market_product_source_bindings(
      workspace_id,
      product_id,
      id,
      market_source_id,
      category_code
    ) on delete cascade,
  constraint market_source_sync_runs_lifecycle_check check (
    (sync_outcome = 'running' and completed_at is null and error_code is null)
    or
    (sync_outcome = 'succeeded' and completed_at is not null and error_code is null)
    or
    (sync_outcome = 'failed' and completed_at is not null and error_code is not null)
  ),
  constraint market_source_sync_runs_time_order_check
    check (completed_at is null or completed_at >= started_at)
);

