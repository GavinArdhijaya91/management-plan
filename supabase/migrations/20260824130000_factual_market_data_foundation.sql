create table public.market_sources (
  id bigint generated by default as identity primary key,
  code text not null unique
    check (code ~ '^[a-z][a-z0-9_]{1,49}$'),
  name text not null
    check (char_length(trim(name)) between 2 and 120),
  homepage_url text not null
    check (homepage_url ~ '^https://' and char_length(homepage_url) <= 2048),
  documentation_url text
    check (
      documentation_url is null
      or documentation_url ~ '^https://' and char_length(documentation_url) <= 2048
    ),
  terms_url text
    check (terms_url is null or terms_url ~ '^https://' and char_length(terms_url) <= 2048),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.market_source_categories (
